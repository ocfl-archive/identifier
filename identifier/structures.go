// Package identifier provides core data structures, filesystem sanitization algorithms,
// technical metadata indexing pipelines, storage abstraction with BadgerDB, and AI/RO-Crate integration.
package identifier

import (
	"fmt"

	"github.com/ocfl-archive/indexer/v3/pkg/indexer"
)

// FileData represents all extracted and enriched metadata for a single indexed file.
// It combines filesystem attributes (path, folder hierarchy, size, modification timestamp)
// with technical analysis results produced by the indexer engine (MIME type, PRONOM ID, checksums, media dimensions).
type FileData struct {
	// Path is the slash-separated relative path of the file from the root data directory.
	Path string `json:"path,omitempty"`

	// Folder is the relative path of the directory containing the file.
	Folder string `json:"folder,omitempty"`

	// Basename is the filename without directory components.
	Basename string `json:"basename,omitempty"`

	// Size is the file size in bytes.
	Size int64 `json:"size,omitempty"`

	// Duplicate indicates whether another file with the exact same content (SHA-512 checksum)
	// has already been encountered during the indexing run.
	Duplicate bool `json:"duplicate,omitempty"`

	// LastMod is the Unix timestamp (seconds since epoch) when the file was last modified.
	LastMod int64 `json:"lastmod,omitempty"`

	// Indexer contains technical identification and extraction results from external tools
	// (Siegfried, FFprobe, ImageMagick identify, Apache Tika, XML/JSON validators).
	Indexer *indexer.ResultV2 `json:"indexer,omitempty"`

	// LastSeen is the Unix timestamp when this file was processed in the current indexing pass.
	LastSeen int64 `json:"lastseen,omitempty"`
}

// AIPerson represents an individual entity identified by AI analysis within a folder context,
// including their name and optional role (e.g. author, performer, composer, recipient).
type AIPerson struct {
	// Name contains the full name of the person, typically in "Lastname, Firstname" format.
	Name string `json:"name"`

	// Role indicates the functional role or contribution of the person in the context of the files.
	Role string `json:"role,omitempty"`
}

// String returns a human-readable representation of the person and role (e.g. "Smith, John [Composer]").
func (p AIPerson) String() string {
	result := p.Name
	if p.Role != "" {
		result += fmt.Sprintf(" [%s]", p.Role)
	}
	return result
}

// AIResultStruct holds structured semantic description metadata generated by LLMs for a specific folder.
// This structure is populated by Genkit structured output flows and saved both to persistent storage
// and export formats (JSONL, CSV, XLSX, RO-Crate metadata).
type AIResultStruct struct {
	// Folder is the relative path of the described folder.
	Folder string `json:"folder"`

	// Title is a concise, descriptive title for the collection of files in this folder.
	Title string `json:"title"`

	// Description provides an academic/archival description of the contents, context, and purpose.
	Description string `json:"description"`

	// Place indicates geographic location(s) associated with the folder contents (if determinable).
	Place string `json:"place,omitempty"`

	// Date represents the single date or date range associated with the folder (format "YYYY", "YYYY-MM-DD", or "YYYY - YYYY").
	Date string `json:"date,omitempty"`

	// Tags is a list of media and thematic classification tags (e.g., "audio", "video", "text", "image", "unknown").
	Tags []string `json:"tags,omitempty"`

	// Persons lists individuals detected or referenced in the folder contents or filenames.
	Persons []AIPerson `json:"persons,omitempty"`

	// Institutions lists organizations, companies, or bodies associated with the contents (in "Name, Place" format).
	Institutions []string `json:"institutions,omitempty"`
}
